const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ts = require("typescript");
const compiled = ts.transpileModule(fs.readFileSync(require.resolve("../lib/saved-properties.ts"), "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2017 } }).outputText;
const context = { exports: {} }; vm.runInNewContext(compiled, context);
const { parseSavedProperties: parse, updateSavedProperties: toggle, SAVED_PROPERTIES_LIMIT: limit } = context.exports;
const plain = (value) => JSON.parse(JSON.stringify(value));
for (const value of [null, "", "bad json", '{}', '"a"', 'null']) assert.deepEqual(plain(parse(value)), []);
assert.deepEqual(plain(parse('["a","a",null,3,"b","../admin","<script>"]')), ["a", "b"]);
const full = Array.from({ length: limit }, (_, i) => `property-${i}`);
assert.equal(parse(JSON.stringify([...full, "overflow"])).length, limit);
assert.equal(toggle(full, "new").result, "limit");
const removed = toggle(full, full[20]);
assert.equal(removed.result, "removed");
assert.equal(removed.ids.length, limit - 1);
assert.equal(full.length, limit, "do not mutate current state");
const added = toggle(removed.ids, "new");
assert.equal(added.result, "added");
assert.equal(added.ids[0], "new", "newest saved property is first");
assert.equal(added.ids.length, limit);
console.log("Saved listings regression checks passed: corrupt storage, unsafe IDs, duplicates, capacity and removal.");
